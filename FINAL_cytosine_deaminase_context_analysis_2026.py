def compute_weighted_position_frequencies(df_sites: pd.DataFrame,
                                           flank_size: int) -> pd.DataFrame:
    """
    Per-position base frequency among ALL observed C->T (or G->A)
    deamination events, weighted by how many times each site was observed
    to be deaminated (n_deaminated). A site with 11 of 40 reads showing
    conversion contributes 11 counts at every flanking position; a site
    with 1 of 23 contributes 1 count. The denominator at every position is
    therefore the total number of deamination observations
    (df_sites['n_deaminated'].sum()), so freq sums to 1.0 across the 4
    bases at each position.

    No genomic-composition correction is applied -- these are the raw
    observed frequencies. See the reference-genome base-composition
    workbook to normalize by hand if desired.
    """
    window       = 2 * flank_size + 1
    total_deam   = int(df_sites["n_deaminated"].sum())
    positions    = [p for p in range(-flank_size, flank_size + 1) if p != 0]

    records = []
    for rel_pos in positions:
        char_idx = rel_pos + flank_size
        weighted_count = Counter()
        for ctx, w in zip(df_sites["context"], df_sites["n_deaminated"]):
            if isinstance(ctx, str) and len(ctx) == window and w > 0:
                weighted_count[ctx[char_idx]] += w
        for base in BASES:
            wc = weighted_count.get(base, 0)
            records.append({
                "position"       : rel_pos,
                "base"           : base,
                "weighted_count" : wc,
                "total_weight"   : total_deam,
                "freq"           : (wc / total_deam) if total_deam > 0 else 0.0,
            })

    return pd.DataFrame(records)


def compute_composition_corrected_frequencies(freq_df: pd.DataFrame,
                                               full_window_counts: Counter,
                                               flank_size: int) -> pd.DataFrame:
    """
    OPTIONAL (plots 09b/10b) -- rescales the raw deamination-weighted
    frequencies in freq_df to remove the genome's own base composition at
    each flanking position, i.e. "as if every base were equally
    represented in the genome at that position."

    For each (position, base):
        p_obs   = observed deamination-weighted frequency (freq_df['freq'])
        p_bg    = genomic background frequency at that position, i.e. how
                  often that base appears at that flanking position across
                  every genomic C (or reverse-complemented G) window --
                  the same population the observed sites are drawn from
        ratio   = p_obs / p_bg   (1.0 = no enrichment; >1 = enriched;
                  <1 = depleted, relative to genome background)
        p_corr  = ratio / sum(ratio over the 4 bases at that position)
                  (renormalized so the 4 bases sum back to 1.0 at each
                  position, giving a value directly usable as a bar/letter
                  height, exactly as freq_df['freq'] is for the
                  uncorrected plots 09/10)

    This does not modify freq_df or the underlying site data -- it is a
    separate, optional rescaling used only for plots 09b/10b.
    """
    pos_base_counts = genomic_position_base_counts(full_window_counts, flank_size)
    positions = [p for p in range(-flank_size, flank_size + 1) if p != 0]

    records = []
    ratios_by_pos = {}
    for rel_pos in positions:
        total_genomic = sum(pos_base_counts[rel_pos].values())
        ratios = {}
        for base in BASES:
            p_obs = freq_df[(freq_df["position"] == rel_pos) &
                             (freq_df["base"] == base)]["freq"].values[0]
            genomic_count = pos_base_counts[rel_pos][base]
            p_bg = (genomic_count / total_genomic) if total_genomic > 0 else 0.0
            ratios[base] = (p_obs / p_bg) if p_bg > 0 else 0.0
        ratios_by_pos[rel_pos] = ratios

    for rel_pos in positions:
        ratios = ratios_by_pos[rel_pos]
        ratio_sum = sum(ratios.values())
        for base in BASES:
            p_obs = freq_df[(freq_df["position"] == rel_pos) &
                             (freq_df["base"] == base)]["freq"].values[0]
            genomic_count = pos_base_counts[rel_pos][base]
            total_genomic = sum(pos_base_counts[rel_pos].values())
            p_bg = (genomic_count / total_genomic) if total_genomic > 0 else 0.0
            ratio = ratios[base]
            p_corr = (ratio / ratio_sum) if ratio_sum > 0 else 0.0
            records.append({
                "position"          : rel_pos,
                "base"              : base,
                "freq_observed"     : p_obs,
                "freq_genomic_bg"   : p_bg,
                "enrichment_ratio"  : ratio,
                "freq_corrected"    : p_corr,
            })

    return pd.DataFrame(records)


def compute_dinucleotide_context_rates(df_sites: pd.DataFrame) -> pd.DataFrame:
    """
    % C->T conversion broken out by the +1 sequence context (CpG / CpA /
    CpC / CpT). For each class: denominator = total read coverage summed
    across every covered site in that class; numerator = total C->T (or
    G->A) observations summed across those same sites. This is a
    coverage-weighted conversion rate per dinucleotide class, using every
    covered site regardless of whether it showed any conversion.
    """
    rows = []
    for ctx_name in DINUC_CONTEXTS:
        base = DINUC_BASE_OF[ctx_name]
        sub  = df_sites[df_sites["context_plus1"] == base]
        n_sites   = len(sub)
        total_cov = int(sub["coverage"].sum())
        total_dea = int(sub["n_deaminated"].sum())
        pct = 100.0 * total_dea / total_cov if total_cov > 0 else 0.0
        rows.append({
            "context"          : ctx_name,
            "n_sites"          : n_sites,
            "total_coverage"   : total_cov,
            "total_deaminated" : total_dea,
            "pct_C_to_T"       : pct,
        })
    return pd.DataFrame(rows)


