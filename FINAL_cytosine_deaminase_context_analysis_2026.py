def get_chromosomes_from_header(bam, user_chroms: list) -> list:
    header = bam.header
    try:
        sq_list   = header.get("SQ", [])
        available = [entry["SN"] for entry in sq_list]
    except Exception:
        available = list(header.get("SQ_names", []))

    if not available:
        print("  WARNING: Could not read chromosome names from BAM header.")
        return user_chroms if user_chroms else []

    print(f"  Reference sequences in BAM: {available}")

    if user_chroms:
        missing = [c for c in user_chroms if c not in available]
        if missing:
            print(f"  WARNING: chromosomes not found in BAM, skipping: {missing}")
        return [c for c in user_chroms if c in available]
    return available


def fetch_context(fasta: pyfaidx.Fasta, chrom: str,
                  pos: int, flank: int) -> str:
    """Return the 2*flank+1 reference sequence centred on pos (0-based)."""
    chrom_len = len(fasta[chrom])
    start, end = pos - flank, pos + flank + 1
    if start < 0 or end > chrom_len:
        return None
    ctx = str(fasta[chrom][start:end]).upper()
    return None if "N" in ctx else ctx


def parse_cigar(read) -> list:
    """
    Walk the CIGAR string and return (query_index, ref_position) pairs
    for every aligned (non-gap) base.
    CIGAR ops: 0=M, 1=I, 2=D, 3=N, 4=S, 5=H
    """
    pairs     = []
    query_pos = 0
    ref_pos   = read.reference_start

    for op, length in read.cigar:
        if op == 0:
            for i in range(length):
                pairs.append((query_pos + i, ref_pos + i))
            query_pos += length
            ref_pos   += length
        elif op == 1:
            query_pos += length
        elif op == 2:
            ref_pos += length
        elif op == 3:
            ref_pos += length
        elif op == 4:
            query_pos += length
        # op == 5 (H): consumes neither

    return pairs


def collect_sites(bam_path: str,
                  ref_path: str,
                  chromosomes: list,
                  flank_size: int,
                  min_bq: int,
                  min_mq: int,
                  min_cov: int) -> pd.DataFrame:
    """
    Iterate over all reads in the BAM. At every reference C (or G for
    minus strand), record how many reads show C/T (or G/A). Aggregate
    into per-site deamination counts with sequence context.

    Every C->T (or G->A) read at a kept site is counted as a deamination
    event directly.

    Only reads that genuinely derive from the strand carrying the cytosine
    in question are counted (gated on BAM FLAG 0x10, i.e. the read's own
    alignment strand): a read from the opposite strand covering the same
    coordinate has no C there at all and can never show a converted base,
    so including it would only inflate coverage without ever contributing
    to the deaminated count.
    """
    print("\n" + "="*60)
    print("Collecting per-site deamination counts")
    print("="*60)

    fasta = pyfaidx.Fasta(ref_path)
    site_data = defaultdict(lambda: {"n_ref": 0, "n_deam": 0, "context": None})

    read_count = skip_count = 0

    with bs.AlignmentFile(bam_path, "rb") as bam:

        chroms_to_use = get_chromosomes_from_header(bam, chromosomes)
        print(f"Processing chromosomes: {chroms_to_use if chroms_to_use else 'ALL'}")
        print("Reading BAM... (may take several minutes for large files)\n")

        for read in bam:

            flag = read.flag
            if flag & 0x4:   skip_count += 1; continue
            if flag & 0x100: skip_count += 1; continue
            if flag & 0x200: skip_count += 1; continue
            if flag & 0x400: skip_count += 1; continue

            try:
                mapq = read.mapq
            except AttributeError:
                try:
                    mapq = read.mapping_quality
                except AttributeError:
                    mapq = 0
            if mapq < min_mq:
                skip_count += 1; continue

            if read.cigar is None:
                skip_count += 1; continue

            try:
                chrom = read.reference_name
            except AttributeError:
                try:
                    chrom = read.rname
                except AttributeError:
                    continue

            if chroms_to_use and chrom not in chroms_to_use:
                continue

            seq       = read.query_sequence
            qualities = read.query_qualities
            if seq is None or qualities is None:
                continue

            read_count += 1
            if read_count % 200_000 == 0:
                print(f"  {read_count:,} reads processed, "
                      f"{len(site_data):,} cytosine sites accumulated...")

            is_reverse = bool(flag & 0x10)

            try:
                pairs = parse_cigar(read)
            except Exception:
                continue

            for q_idx, r_pos in pairs:
                if q_idx >= len(seq) or q_idx >= len(qualities):
                    continue
                if qualities[q_idx] < min_bq:
                    continue

                read_base = seq[q_idx].upper()

                try:
                    ref_base = str(fasta[chrom][r_pos]).upper()
                except Exception:
                    continue

                # A read is only informative about a given reference C (or G)
                # if it actually derives from the strand that physically has a
                # cytosine at this coordinate. A read from the OPPOSITE strand
                # covering the same position has no C there at all (it has the
                # complementary base), so an unconverted copy of it will
                # always display the reference base after standard SAM
                # reverse-complementing -- it can never show a "converted"
                # signal, and including it would only pad the coverage
                # denominator without ever contributing to the deaminated
                # count. Gate on the read's own alignment strand (FLAG 0x10)
                # to exclude these uninformative reads entirely.
                if ref_base == "C" and not is_reverse and read_base in ("C", "T"):
                    key = (chrom, r_pos, "+")
                    if site_data[key]["context"] is None:
                        ctx = fetch_context(fasta, chrom, r_pos, flank_size)
                        if ctx is None:
                            continue
                        site_data[key]["context"] = ctx
                    if read_base == "T":
                        site_data[key]["n_deam"] += 1
                    else:
                        site_data[key]["n_ref"] += 1

                elif ref_base == "G" and is_reverse and read_base in ("G", "A"):
                    key = (chrom, r_pos, "-")
                    if site_data[key]["context"] is None:
                        ctx_plus = fetch_context(fasta, chrom, r_pos, flank_size)
                        if ctx_plus is None:
                            continue
                        site_data[key]["context"] = reverse_complement(ctx_plus)
                    if read_base == "A":
                        site_data[key]["n_deam"] += 1
                    else:
                        site_data[key]["n_ref"] += 1

    print(f"\n  Reads processed : {read_count:,}")
    print(f"  Reads skipped   : {skip_count:,}")
    print(f"  Raw sites found : {len(site_data):,}")

    center_idx = flank_size
    plus1_idx  = flank_size + 1

    records = []
    for (chrom, pos, strand), v in site_data.items():
        total = v["n_ref"] + v["n_deam"]
        if total < min_cov or v["context"] is None:
            continue
        ctx = v["context"]
        records.append({
            "chrom"          : chrom,
            "pos"            : pos,
            "strand"         : strand,
            "reference"      : "C" if strand == "+" else "G",
            "coverage"       : total,
            "n_deaminated"   : v["n_deam"],
            "n_ref"          : v["n_ref"],
            "conv_rate"      : v["n_deam"] / total,
            "context"        : ctx,
            "context_plus1"  : ctx[plus1_idx],
        })

    df = pd.DataFrame(records)
    print(f"  Sites passing coverage >= {min_cov}: {len(df):,}")
    if len(df):
        print(f"  Total deamination observations (sum of n_deaminated): "
              f"{df['n_deaminated'].sum():,}")
    return df


def count_genome_base_composition(ref_path: str, chromosomes: list) -> Counter:
    """
    Whole-genome (or whole-selected-chromosome-set) A/C/G/T base counts,
    scanned directly from the reference FASTA. Independent of the BAM,
    the enzyme reaction, and the +/-flank window used elsewhere in this
    script -- this is simply "how much A, C, G, and T is in the reference
    sequence(s) analysed," so you can apply any composition normalization
    you want by hand to the deamination-weighted results below.
    """
    print("  Scanning reference genome for whole-sequence base composition...")
    fasta  = pyfaidx.Fasta(ref_path)
    chroms = chromosomes if chromosomes else list(fasta.keys())

    counts = Counter()
    for chrom in chroms:
        seq = str(fasta[chrom][:].seq).upper()
        for base in BASES:
            counts[base] += seq.count(base)
        print(f"    {chrom}: {len(seq):,} bp")

    total = sum(counts.values())
    print(f"  Total A/C/G/T bases counted: {total:,}")
    return counts


def count_genomic_position_composition(ref_path: str,
                                        chromosomes: list,
                                        flank_size: int) -> Counter:
    """
    Scan the reference FASTA and count the full (2*flank_size+1)-mer
    context around every genomic C (using the reverse complement around
    every genomic G, so everything is oriented 5'->3' with C at the
    centre). This is purely descriptive genomic-composition information --
    it is reported alongside the deamination-weighted heatmap/logo so you
    can normalize by hand if desired, but it is NOT used to correct or
    rescale any of the deamination-weighted results in this script.
    """
    print("  Scanning reference genome for cytosine-window context counts...")
    fasta  = pyfaidx.Fasta(ref_path)
    window = 2 * flank_size + 1

    full_window_counts = Counter()
    chroms = chromosomes if chromosomes else list(fasta.keys())

    for chrom in chroms:
        seq       = str(fasta[chrom][:].seq).upper()
        chrom_len = len(seq)
        print(f"    {chrom}: {chrom_len:,} bp", end=" ... ")

        fwd_count = rev_count = 0
        for pos in range(flank_size, chrom_len - flank_size):
            base = seq[pos]
            if base == "C":
                ctx = seq[pos - flank_size: pos + flank_size + 1]
                if len(ctx) == window and "N" not in ctx:
                    full_window_counts[ctx] += 1
                    fwd_count += 1
            elif base == "G":
                ctx_plus = seq[pos - flank_size: pos + flank_size + 1]
                if len(ctx_plus) == window and "N" not in ctx_plus:
                    ctx_rc = ctx_plus.translate(COMPLEMENT)[::-1]
                    full_window_counts[ctx_rc] += 1
                    rev_count += 1

        print(f"{fwd_count:,} fwd C + {rev_count:,} rev C")

    total = sum(full_window_counts.values())
    print(f"  Total genomic cytosine-window contexts counted: {total:,}")
    return full_window_counts


def genomic_position_base_counts(full_window_counts: Counter, flank_size: int) -> dict:
    """
    Marginal genomic base count at each flanking position (-flank_size to
    +flank_size, skipping 0), derived from the full-window context counts
    above. Purely descriptive/reference information for manual
    normalization -- not used to correct any plotted value.
    """
    window = 2 * flank_size + 1
    pos_counts = {}
    for rel_pos in range(-flank_size, flank_size + 1):
        if rel_pos == 0:
            continue
        char_idx = rel_pos + flank_size
        counts = Counter()
        for ctx, n in full_window_counts.items():
            if len(ctx) == window:
                counts[ctx[char_idx]] += n
        pos_counts[rel_pos] = {b: counts.get(b, 0) for b in BASES}
    return pos_counts


