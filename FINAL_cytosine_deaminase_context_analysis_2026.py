_LOGO_LETTER_FONT = FontProperties(family="Arial", weight="bold")


def _add_logo_letter(ax, letter: str, x: float, y0: float, height: float,
                      width: float, color: str):
    """
    Draw a single letter as a filled glyph path, non-uniformly scaled to
    exactly fill a width x height box centred at x with its bottom edge at
    y0. This is what makes the letter itself act as the colored "bar" —
    as in a traditional sequence logo — rather than a colored rectangle
    with a small text label on top of it.
    """
    if height <= 0:
        return
    tp = TextPath((0, 0), letter, size=1, prop=_LOGO_LETTER_FONT)
    bbox = tp.get_extents()
    if bbox.width == 0 or bbox.height == 0:
        return
    transform = (Affine2D()
                 .translate(-bbox.x0, -bbox.y0)
                 .scale(width / bbox.width, height / bbox.height)
                 .translate(x - width / 2, y0)
                 + ax.transData)
    ax.add_patch(PathPatch(tp, transform=transform, facecolor=color,
                            edgecolor="none", lw=0))


def plot_sequence_logo(freq_df: pd.DataFrame, flank_size: int, out_dir: str):
    """
    PLOT 10 — Letter-glyph sequence logo of ALL observed C->T deamination
    events, weighted by how many times each site was observed deaminated
    (n_deaminated). Bar/letter heights are the plain observed frequency at
    each position (freq_df['freq'], which sums to 1.0 across A/C/G/T at
    every position) -- no information-content rescaling and no genomic-
    composition correction, so every column always stacks to a full height
    of 1.0. Bases are always stacked in the same fixed vertical order
    (T bottom, G, C, A top) and colored with the standard Sanger/ABI trace
    convention.
    """
    positions = [p for p in range(-flank_size, flank_size + 1) if p != 0]

    fig, ax = plt.subplots(figsize=(1.05 * (2 * flank_size + 1) + 1, 4.2))
    letter_width = 0.82
    gap_frac = 0.03  # small visual gap between stacked letters

    for pos in positions:
        sub = freq_df[freq_df["position"] == pos]
        freqs = {b: (sub[sub["base"] == b]["freq"].values[0]
                     if len(sub[sub["base"] == b]) else 0.0) for b in BASES}

        bottom = 0.0
        for base in LOGO_STACK_ORDER_BOTTOM_TO_TOP:
            h = freqs[base]
            if h <= 0:
                continue
            gap = h * gap_frac
            _add_logo_letter(ax, base, pos, bottom + gap / 2, h - gap,
                             letter_width, SANGER_BASE_COLORS[base])
            bottom += h

    # Position 0: fixed C -> U marker (not data-derived -- every counted
    # observation is, by construction, a C converting to a T/U read).
    ax.text(0, 0.72, "C", ha="center", va="center", fontsize=22,
            fontweight="bold", color="black")
    ax.annotate("", xy=(0, 0.30), xytext=(0, 0.58),
                arrowprops=dict(arrowstyle="-|>", color="black", lw=2))
    ax.text(0, 0.14, "U", ha="center", va="center", fontsize=22,
            fontweight="bold", color="black")

    all_x = list(range(-flank_size, flank_size + 1))
    ax.set_xticks(all_x)
    ax.set_xticklabels([str(p) for p in all_x], fontsize=11)
    ax.set_xlim(-flank_size - 0.6, flank_size + 0.6)
    ax.set_ylim(0, 1.0)
    ax.set_ylabel("Deamination-weighted frequency", fontsize=12)
    ax.set_xlabel("Position relative to deaminated C", fontsize=12)
    ax.set_title(
        "Sequence Logo — All Observed C→T Deamination Events\n"
        "(height scaled to observed frequency; weighted by n_deaminated per site)",
        fontsize=12, fontweight="bold")
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    plt.tight_layout()
    path = os.path.join(out_dir, "10_sequence_logo.pdf")
    fig.savefig(path, bbox_inches="tight")
    plt.show()
    print(f"  Saved: {path}")


