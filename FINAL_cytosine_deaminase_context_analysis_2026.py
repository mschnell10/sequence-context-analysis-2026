"""
=============================================================================
Cytosine Deaminase Sequence Context Preference Analysis
=============================================================================
Purpose:
    Analyzes a BAM file generated by Bismark alignment (used here purely as
    a C->T mismatch-tolerant aligner, NOT for bisulfite sequencing) to
    determine the sequence context preference of a cytosine deaminase
    enzyme.

Biological model:
    - Your enzyme deaminates cytosine (C) to uracil (U), which is read as
      thymine (T) during sequencing.
    - Every C->T mismatch in a read relative to the reference is treated as
      a deamination event.
    - There is NO bisulfite chemistry in this experiment. Bismark is used
      only because it aligns reads containing C->T changes without
      penalising them as mismatches.

Notes:
      Every reference C (or G on the minus strand) covered at
      >= MIN_COVERAGE reads is kept, and every C->T (or G->A) read at that
      site is counted as a deamination event — no thresholding, no
      "called" vs. "background" distinction.
    - The script reports the reference genome's own
      base composition (genome-wide, and position-by-position across the
      +/-3 flanking window) in a standalone workbook, so you can apply any
      normalization you want by hand.
    - The sequence logo and position-frequency heatmap (plots 9 and 10) are weighted by
      the number of deamination observations at each site (n_deaminated. A site with 11 of 40 reads
      showing C->T contributes 11 counts to the logo; a site with 1 of 23
      contributes 1 count. Heights are plain observed frequencies.
    - A plot/table reports % C->T conversion broken out by the +1
      sequence context (CpG / CpA / CpC / CpT): for each dinucleotide
      class, all covered-site read coverage in that class is the
      denominator and all C->T observations in that class are the
      numerator.
    - (optional): plots 09b/10b. Plots 09/10 use raw observed
      frequencies with no genome-composition correction. Setting
      GENERATE_COMPOSITION_CORRECTED = True in Cell 1's CONFIG additionally
      produces 09b/10b: the same heatmap and logo, but with each flanking
      position's base frequencies divided by that position's own genomic
      background frequency (from the reference genome's C-window
      composition) and renormalized to sum to 1 -- i.e. "as if every base
      were equally represented in the genome at that position." This adds
      two extra plots/workbooks alongside 09/10; it does not replace them.

How to use this script in Spyder (organized into 3 cells, run in order):

    CELL 1 (always run first): imports, config, and helper function
    definitions. No heavy computation happens here.

    CELL 2 (slow — scans the BAM and the reference genome once):
    Collects per-site C->T counts from the treated BAM and scans the
    reference FASTA for genome-wide and position-wise base composition.
    Re-run this only if you change the BAM/FASTA paths or the read-
    filtering config in Cell 1.

    CELL 3 (fast — re-run freely once Cell 2 has been run):
    Computes the deamination-weighted position frequencies and +1-context
    conversion rates, generates plots 09/10/11, and writes all Excel/CSV
    outputs.

Pipeline context:
    Input BAM file processed through:
      - Bismark genome preparation (C->T and G->A converted genomes)
      - TrimGalore! trimming
      - Bismark Bowtie2 alignment
      - Picard sorting + MarkDuplicates deduplication

Requirements:
    pip install bamnostic pyfaidx numpy pandas matplotlib openpyxl

=============================================================================
"""

