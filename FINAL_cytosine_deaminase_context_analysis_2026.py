def plot_position_frequency_heatmap(freq_df: pd.DataFrame, flank_size: int, out_dir: str):
    """
    PLOT 09 — Deamination-observation-weighted base frequency at each
    flanking position (-3 to +3, skipping 0). No genomic-composition
    correction is applied; the color scale is simply centred at 0.25 as a
    visual reference for "equal representation of all 4 bases," which is
    only the correct "no preference" baseline if the genome itself has an
    even base composition at that position (see the reference-genome
    base-composition workbook).
    """
    positions = [p for p in range(-flank_size, flank_size + 1) if p != 0]
    mat = np.zeros((4, len(positions)))
    for j, pos in enumerate(positions):
        sub = freq_df[freq_df["position"] == pos]
        for i, base in enumerate(BASES):
            val = sub[sub["base"] == base]["freq"]
            mat[i, j] = val.values[0] if len(val) else 0.0

    # Figure size in inches -- this is the main lever for the plot's overall
    # printed size (each box's physical size = figsize / grid dimensions,
    # after axes/label/colorbar margins). Shrink this to make the whole
    # plot (and every box in it) smaller.
    fig, ax = plt.subplots(figsize=(5.5, 2.3))
    cmap = plt.cm.RdBu_r
    # Color scale fixed to 0-1 regardless of the data, so multiple samples
    # plotted separately always share the same scale and are directly
    # comparable. (Previously this adapted to the data: vmax = max(0.5,
    # mat.max()), so two samples could end up on different scales.)
    norm = TwoSlopeNorm(vmin=0.0, vcenter=0.25, vmax=1.0)

    # Draw the heatmap as individual colored rectangles rather than
    # ax.imshow(), so it stays vector (editable) in PDF output rather than
    # importing as a single embedded raster image.
    # box_pad shrinks each box below the full 1x1 grid cell, leaving a
    # visible gap between adjacent boxes. 0.0 = boxes touch edge-to-edge;
    # a thin black border (rather than white) keeps adjacent similar-
    # valued boxes visually distinct even with zero gap between them.
    box_pad = 0.0
    box_w = box_h = 1 - box_pad
    n_rows = mat.shape[0]
    total_cols = 2 * flank_size + 1  # includes an empty column for position 0
    for i in range(n_rows):
        for j, pos in enumerate(positions):
            col = pos + flank_size  # skips column index flank_size (position 0)
            color = cmap(norm(mat[i, j]))
            ax.add_patch(mpatches.Rectangle(
                (col - box_w / 2, i - box_h / 2), box_w, box_h,
                facecolor=color, edgecolor="black", linewidth=0.25))
            val = mat[i, j]
            text_color = "black" if 0.15 < val < 0.40 else "white"
            ax.text(col, i, f"{val:.2f}", ha="center", va="center",
                    fontsize=8, color=text_color, fontweight="bold")

    # Position 0 is deliberately left as an empty gap column (no box drawn)
    # for a C -> U indicator to be added manually in Illustrator, matching
    # the gap already present at position 0 in plots 10/10b.
    ax.set_xlim(-0.5, total_cols - 0.5)
    ax.set_ylim(n_rows - 0.5, -0.5)
    ax.set_xticks(range(total_cols))
    ax.set_xticklabels([str(p) for p in range(-flank_size, flank_size + 1)], fontsize=10)
    ax.set_yticks(range(4))
    ax.set_yticklabels(BASES, fontsize=10)
    ax.set_xlabel("Position relative to deaminated C (0)", fontsize=10)
    ax.set_ylabel("Nucleotide", fontsize=10)
    # Mirror the left/bottom axis spines on the top/right so the heatmap
    # is fully enclosed in a rectangular border (same default weight/color
    # as the existing spines, not a separately-styled line).
    ax.spines["top"].set_visible(True)
    ax.spines["right"].set_visible(True)

    sm = plt.cm.ScalarMappable(cmap=cmap, norm=norm)
    sm.set_array([])
    cbar = fig.colorbar(sm, ax=ax, fraction=0.03, pad=0.02)
    # Explicit ticks so 0.1 and 0.25 land at their correct (non-linear,
    # TwoSlopeNorm) positions alongside the standard 0.2-spaced values.
    cbar.set_ticks([0.0, 0.1, 0.2, 0.25, 0.4, 0.6, 0.8, 1.0])
    cbar.ax.tick_params(labelsize=8)
    cbar.ax.axhline(0.25, color="black", linewidth=1.5, linestyle="--")
    # No colorbar label and no plot title -- trimmed for a more compact,
    # Illustrator-ready default output.

    plt.tight_layout()
    path = os.path.join(out_dir, "09_position_frequency_heatmap.pdf")
    fig.savefig(path, bbox_inches="tight")
    plt.show()
    print(f"  Saved: {path}")


