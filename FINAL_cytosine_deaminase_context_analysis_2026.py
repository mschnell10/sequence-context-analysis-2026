        "  count / total_weight; freq sums to 1.0 across A/C/G/T at each position.",
        "",
        "Heatmap_Matrix: the same freq values laid out as a base x position grid,",
        "  matching the layout of the plotted figure. No genomic-composition",
        "  correction is applied anywhere in this workbook.",
        "",
        "Genomic_Position_Composition: reference-only information -- how often each",
        "  base appears at each flanking position across every genomic C (or G) window",
